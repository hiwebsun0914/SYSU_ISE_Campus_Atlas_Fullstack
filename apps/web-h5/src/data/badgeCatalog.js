export function badgeThumb(url, size = 256, quality = 75) {
  if (!url) return ''
  const transform = `imageMogr2/thumbnail/${size}x/format/webp/quality/${quality}`
  return url.includes('?') ? `${url}&${transform}` : `${url}?${transform}`
}

export function getBadge(locationId) {
  const id = Number(locationId)
  return badgeCatalog.find(item => item.id === id) || null
}
